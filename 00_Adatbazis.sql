BEGIN
    EXEC(N'CREATE DATABASE [PY_2]');
    EXEC(N'ALTER DATABASE [PY_2] SET COMPATIBILITY_LEVEL = 160');
    EXEC(N'IF (1 = FULLTEXTSERVICEPROPERTY(''IsFullTextInstalled''))
begin
EXEC [PY_2].[dbo].[sp_fulltext_database] @action = ''enable''
end');
    EXEC(N'ALTER DATABASE [PY_2] SET ANSI_NULL_DEFAULT OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET ANSI_NULLS OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET ANSI_PADDING OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET ANSI_WARNINGS OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET ARITHABORT OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET AUTO_CLOSE OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET AUTO_SHRINK OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET AUTO_UPDATE_STATISTICS ON');
    EXEC(N'ALTER DATABASE [PY_2] SET CURSOR_CLOSE_ON_COMMIT OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET CURSOR_DEFAULT  GLOBAL');
    EXEC(N'ALTER DATABASE [PY_2] SET CONCAT_NULL_YIELDS_NULL OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET NUMERIC_ROUNDABORT OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET QUOTED_IDENTIFIER OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET RECURSIVE_TRIGGERS OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET  DISABLE_BROKER');
