    EXEC(N'ALTER DATABASE [PY_2] SET RECOVERY FULL');
    EXEC(N'ALTER DATABASE [PY_2] SET  MULTI_USER');
    EXEC(N'ALTER DATABASE [PY_2] SET PAGE_VERIFY CHECKSUM');
    EXEC(N'ALTER DATABASE [PY_2] SET DB_CHAINING OFF');
    EXEC(N'ALTER DATABASE [PY_2] SET FILESTREAM( NON_TRANSACTED_ACCESS = OFF )');
    EXEC(N'ALTER DATABASE [PY_2] SET TARGET_RECOVERY_TIME = 60 SECONDS');
    EXEC(N'ALTER DATABASE [PY_2] SET DELAYED_DURABILITY = DISABLED');
    EXEC(N'ALTER DATABASE [PY_2] SET ACCELERATED_DATABASE_RECOVERY = OFF');
    EXEC(N'EXEC sys.sp_db_vardecimal_storage_format N''PY_2'', N''ON''');
    EXEC(N'ALTER DATABASE [PY_2] SET QUERY_STORE = ON');
    EXEC(N'ALTER DATABASE [PY_2] SET QUERY_STORE (OPERATION_MODE = READ_WRITE, CLEANUP_POLICY = (STALE_QUERY_THRESHOLD_DAYS = 30), DATA_FLUSH_INTERVAL_SECONDS = 900, INTERVAL_LENGTH_MINUTES = 60, MAX_STORAGE_SIZE_MB = 1000, QUERY_CAPTURE_MODE = AUTO, SIZE_BASED_CLEANUP_MODE = AUTO, MAX_PLANS_PER_QUERY = 200, WAIT_STATS_CAPTURE_MODE = ON)');
